#!/usr/bin/env python3
"""Build SKILLS.md: the list of every skill and always-on rule in this kit.

The catalog is generated from the skill files themselves, so it never goes out of date:
    python3 tools/build_catalog.py          # rewrite SKILLS.md
    python3 tools/build_catalog.py --check  # exit 1 if SKILLS.md is out of date (used in CI)

Sources:
    skills/*/SKILL.md      name, description, metadata (owner, version), and the body's
                           "## " headings, which are listed as the skill's rules
    templates/AGENTS.md    the always-on rules (its top-level bullet points)
Standard library only.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from validate_skill import find_skills, parse_frontmatter  # noqa: E402

ROOT = HERE.parent
SKILLS_DIR = ROOT / "skills"
AGENTS = ROOT / "templates" / "AGENTS.md"
OUT = ROOT / "SKILLS.md"


def first_sentence(text: str) -> str:
    m = re.match(r"(.+?\.)(\s|$)", text.strip())
    return m.group(1) if m else text.strip()


def when_to_use(text: str) -> str:
    m = re.search(r"\b(Use (?:for|when|this)\b.*)", text)
    return m.group(1).strip() if m else ""


def skill_rules(body: str) -> list[str]:
    rules = []
    for line in body.splitlines():
        m = re.match(r"^##\s+(.+?)\s*$", line)
        if m:
            rules.append(re.sub(r"^\d+\.\s*", "", m.group(1)))
    return rules


def agents_rules() -> list[str]:
    if not AGENTS.is_file():
        return []
    rules, current = [], None
    for line in AGENTS.read_text(encoding="utf-8").splitlines():
        if line.startswith("- "):
            current = line[2:].strip()
            rules.append(current)
        elif current is not None and line.startswith("  ") and line.strip():
            rules[-1] += " " + line.strip()
        else:
            current = None
    return rules


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def build() -> str:
    skills = []
    for d in find_skills(SKILLS_DIR):
        fm, body = parse_frontmatter((d / "SKILL.md").read_text(encoding="utf-8"))
        meta = fm.get("metadata") if isinstance(fm.get("metadata"), dict) else {}
        extras = sorted(p.relative_to(d).as_posix() for p in d.rglob("*")
                        if p.is_file() and p.name != "SKILL.md")
        skills.append({
            "name": fm.get("name", d.name), "dir": d.relative_to(ROOT).as_posix(),
            "description": fm.get("description", ""), "version": meta.get("version", "-"),
            "owner": meta.get("owner", "-"), "based_on": meta.get("based-on", ""),
            "rules": skill_rules(body), "extras": extras,
        })

    out = [
        "# Skills catalog",
        "",
        "Every skill and always-on rule in this kit. New to the kit? Start with the "
        "[beginner's guide](README.md). Want to add or change a skill? See "
        "[CONTRIBUTING.md](CONTRIBUTING.md).",
        "",
        "<!-- Generated by tools/build_catalog.py from the skill files. Do not edit by hand. -->",
        "",
        f"## Skills ({len(skills)})",
        "",
        "| Skill | What it does | Version | Owner |",
        "| --- | --- | --- | --- |",
    ]
    for s in skills:
        out.append(f"| [{s['name']}](#{s['name']}) | {cell(first_sentence(s['description']))} | "
                   f"{s['version']} | {s['owner']} |")

    rules = agents_rules()
    out += [
        "",
        "## Always-on rules",
        "",
        "These live in [`templates/AGENTS.md`](templates/AGENTS.md). Copy that file into a project "
        "folder so the AI follows them on every task; the skills hold the detail.",
        "",
    ]
    out += [f"{i}. {r}" for i, r in enumerate(rules, 1)] or ["_No AGENTS.md found._"]

    out += ["", "## Skill details", ""]
    for s in skills:
        out += [f"### {s['name']}", ""]
        out.append(first_sentence(s["description"]))
        use = when_to_use(s["description"])
        if use:
            phrase = use[4:] if use.startswith("Use ") else use
            out += ["", f"**When it's used:** {phrase[:1].upper()}{phrase[1:]}"]
        out += ["", f"**Version:** {s['version']} · **Owner:** {s['owner']} · "
                    f"**Files:** [`{s['dir']}/`]({s['dir']}/SKILL.md)"]
        if s["based_on"]:
            out += ["", f"**Based on:** {s['based_on']}"]
        if s["rules"]:
            out += ["", "**Rules:**", ""] + [f"- {r}" for r in s["rules"]]
        if s["extras"]:
            out += ["", "**Extra files:** " + ", ".join(f"`{e}`" for e in s["extras"])]
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("SKILLS.md is out of date. Run: python3 tools/build_catalog.py")
            return 1
        print("SKILLS.md is up to date.")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
